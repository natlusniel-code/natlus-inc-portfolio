import { getSingleton, listItems } from "./content.ts";
import type {
  Benefit,
  CeoProfile,
  CompanySettings,
  ContactInfo,
  ContentBundle,
  Faq,
  FooterContent,
  HeroContent,
  PricingNote,
  PricingPackage,
  ProcessStep,
  Project,
  SeoSettings,
  Service,
  SiteSettings,
  SocialLink,
  Testimonial,
  WhatsAppTemplates,
} from "../../shared/types.ts";

export async function getPublicBundle(): Promise<ContentBundle> {
  const [
    company,
    ceo,
    hero,
    contact,
    whatsapp,
    footer,
    seo,
    settings,
    pricing,
    portfolioCategories,
    services,
    packages,
    projects,
    process,
    benefits,
    testimonials,
    faqs,
    socials,
  ] = await Promise.all([
    getSingleton<CompanySettings>("company"),
    getSingleton<CeoProfile>("ceo"),
    getSingleton<HeroContent>("hero"),
    getSingleton<ContactInfo>("contact"),
    getSingleton<WhatsAppTemplates>("whatsapp"),
    getSingleton<FooterContent>("footer"),
    getSingleton<SeoSettings>("seo"),
    getSingleton<SiteSettings>("settings"),
    getSingleton<PricingNote>("pricing"),
    getSingleton<string[]>("portfolioCategories"),
    listItems<Service>("services"),
    listItems<PricingPackage>("packages"),
    listItems<Project>("projects"),
    listItems<ProcessStep>("process"),
    listItems<Benefit>("benefits"),
    listItems<Testimonial>("testimonials"),
    listItems<Faq>("faqs"),
    listItems<SocialLink>("socials"),
  ]);

  return {
    company,
    ceo,
    hero,
    contact,
    whatsapp,
    footer,
    seo,
    settings,
    pricing,
    portfolioCategories,
    services,
    packages,
    projects,
    process,
    benefits,
    testimonials,
    faqs,
    socials,
  };
}
